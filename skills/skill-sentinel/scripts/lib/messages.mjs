const CATALOG = { en, ar };

const CONTEXT_NOTE = {
  en: { quoted: " (quoted — likely an example; confirm)", described: " (described — likely documentation; confirm)", negated: " (negated — likely guidance; confirm)" },
  ar: { quoted: " (مقتبس — غالباً مثال؛ تأكد)", described: " (موصوف — غالباً توثيق؛ تأكد)", negated: " (منفي — غالباً إرشاد؛ تأكد)" },
};

export function message(code, params = {}, lang = "en") {
  const table = CATALOG[lang] ?? en;
  const render = table[code] ?? en[code];
  const note = params.context ? ((CONTEXT_NOTE[lang] ?? CONTEXT_NOTE.en)[params.context] ?? "") : "";
  return render ? render(params) + note : code;
}

export const LANGUAGES = Object.keys(CATALOG);
